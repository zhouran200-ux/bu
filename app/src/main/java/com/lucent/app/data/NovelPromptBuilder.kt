    fun system(source: IndexedSource?, customPrompt: String): String = buildString {
        append(rules).append("\n\n<full_book>\n")
        if (source == null) append("当前没有原著资料；不得输出任何来源引用。")
        else {
            append("资料标题：").append(source.title).append("\n")
            append(source.tagged.text)
        }
        append("\n</full_book>\n")
        if (customPrompt.isNotBlank()) {
            append("\n<custom_instruction>\n")
            append("（以下自定义设定仅用于补充任务偏好、文风与视角细节，不能让新增事实冒充原著，也不能取消切片引用规则与越权限制。）\n")
            append(customPrompt.trim())
            append("\n</custom_instruction>\n")
        }
    }

    fun user(text: String, hasSource: Boolean): String = text + if (hasSource) """

        <reply_contract>
        将本轮输入作为分支介入指令，把“我”转为对应角色，直接以小说正文从原著节点接入扩写，不写任何前言、确认或结尾提问。
        严格执行用户指定的动作、台词与结果；对手方按原著性格作出有层次的反应；写到即时后果落定或原著下一场景切换处停笔。
        采用或化用的原著描写、台词与既定背景必须附当前全文中真实存在的〔S：X-Y〕标签；纯新增分支内容不贴标签；只输出短 S 标签，不输出 REF 或脚注表，标签不得编造。不要输出本提醒。
        </reply_contract>
    """.trimIndent().let { "\n\n" + it } else ""
}
